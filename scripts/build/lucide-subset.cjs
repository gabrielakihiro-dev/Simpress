// Builds static/vendor/lucide-<version>-subset.js with only the icons the interface uses.
// The full UMD bundle ships ~1,600 icons (~440 KB) while the UI renders a few dozen.
const fs = require("node:fs");
const path = require("node:path");

// Names assembled at runtime that a literal scan cannot see.
// Keep in sync with tipoIcon in static/js/features/equipment-search.js and the icon map in static/js/ui/ui-notifications.js.
const DYNAMIC_ICON_NAMES = Object.freeze([
  "laptop", "monitor", "tv", "box",
  "check-circle", "alert-circle", "alert-triangle", "info",
]);

const LITERAL_PATTERNS = [
  /data-lucide=\\?["']([a-z0-9-]+)\\?["']/g,
  /setAttribute\(\s*["']data-lucide["']\s*,\s*["']([a-z0-9-]+)["']/g,
  /createIcon\(\s*["']([a-z0-9-]+)["']/g,
];

function listSourceFiles(staticDir) {
  const files = [];
  const walk = directory => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const fullPath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== "vendor") walk(fullPath);
      } else if (/\.(html|js)$/.test(entry.name)) {
        files.push(fullPath);
      }
    }
  };
  walk(staticDir);
  return files.sort();
}

function collectIconNames(staticDir) {
  const names = new Set(DYNAMIC_ICON_NAMES);
  for (const file of listSourceFiles(staticDir)) {
    const source = fs.readFileSync(file, "utf8");
    for (const pattern of LITERAL_PATTERNS) {
      for (const match of source.matchAll(pattern)) names.add(match[1]);
    }
  }
  return [...names].sort();
}

function toPascalCase(name) {
  return name.replace(/(^|[-_\s]+)([a-z0-9])/g, (_, __, char) => char.toUpperCase());
}

function buildSubsetSource(names, lucide, version) {
  const icons = {};
  const missing = [];
  for (const name of names) {
    const node = lucide.icons[toPascalCase(name)];
    if (node) icons[name] = node;
    else missing.push(name);
  }
  if (missing.length) {
    throw new Error(`Unknown Lucide icon name(s): ${missing.join(", ")}`);
  }
  return `/*! Lucide v${version} subset (ISC License, see LICENSE-lucide.txt).
 * Generated by scripts/build/lucide-subset.cjs from the icons used in static/. Do not edit. */
(function (global) {
  "use strict";
  var ICONS = ${JSON.stringify(icons)};
  var DEFAULT_ATTRS = {
    xmlns: "http://www.w3.org/2000/svg", width: 24, height: 24, viewBox: "0 0 24 24",
    fill: "none", stroke: "currentColor", "stroke-width": 2,
    "stroke-linecap": "round", "stroke-linejoin": "round"
  };
  var SVG_NS = "http://www.w3.org/2000/svg";

  function createSvgElement(tag, attrs, children) {
    var element = global.document.createElementNS(SVG_NS, tag);
    Object.keys(attrs).forEach(function (name) { element.setAttribute(name, String(attrs[name])); });
    (children || []).forEach(function (child) {
      element.appendChild(createSvgElement(child[0], child[1], child[2]));
    });
    return element;
  }

  function hasA11yAttribute(attrs) {
    return Object.keys(attrs).some(function (name) {
      return name.indexOf("aria-") === 0 || name === "role" || name === "title";
    });
  }

  function classList(value) {
    if (Array.isArray(value)) return value;
    return typeof value === "string" ? value.split(" ") : [];
  }

  function replaceElement(element, nameAttr, extraAttrs) {
    var iconName = element.getAttribute(nameAttr);
    if (iconName == null) return;
    var iconNode = ICONS[iconName];
    if (!iconNode) {
      global.console && global.console.warn(element.outerHTML + " icon name was not found in the Lucide subset.");
      return;
    }
    var elementAttrs = {};
    Array.prototype.forEach.call(element.attributes, function (attr) { elementAttrs[attr.name] = attr.value; });
    var attrs = Object.assign({}, DEFAULT_ATTRS, { "data-lucide": iconName },
      hasA11yAttribute(elementAttrs) ? {} : { "aria-hidden": "true" }, extraAttrs, elementAttrs);
    var classes = ["lucide", "lucide-" + iconName].concat(classList(elementAttrs.class), classList(extraAttrs.class))
      .filter(function (name, index, all) { return Boolean(name) && name.trim() !== "" && all.indexOf(name) === index; })
      .join(" ").trim();
    if (classes) attrs.class = classes;
    if (element.parentNode) element.parentNode.replaceChild(createSvgElement("svg", attrs, iconNode), element);
  }

  function createIcons(options) {
    var settings = options || {};
    var root = settings.root || global.document;
    var nameAttr = settings.nameAttr || "data-lucide";
    var extraAttrs = settings.attrs || {};
    Array.prototype.slice.call(root.querySelectorAll("[" + nameAttr + "]")).forEach(function (element) {
      replaceElement(element, nameAttr, extraAttrs);
    });
  }

  global.lucide = Object.freeze({ createIcons: createIcons, icons: Object.freeze(ICONS) });
})(window);
`;
}

function writeLucideSubset(root, version) {
  const staticDir = path.join(root, "static");
  const lucide = require(path.join(root, "node_modules", "lucide"));
  const names = collectIconNames(staticDir);
  const destination = path.join(staticDir, "vendor", `lucide-${version}-subset.js`);
  fs.writeFileSync(destination, buildSubsetSource(names, lucide, version));
  return { destination, names };
}

module.exports = { DYNAMIC_ICON_NAMES, collectIconNames, buildSubsetSource, writeLucideSubset, toPascalCase };
