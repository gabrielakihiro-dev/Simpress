"""Generate only fictional files for the migration rehearsal."""

import json
import importlib
from pathlib import Path
from typing import Any
import uuid

from persistence.comparison_history import CATEGORIES
from persistence.migration import sha
from persistence.postgres import canonical
from scripts.verify_storage_pilot import inventory, xlsx


def generate(root, domain):
    root = Path(root)
    root.mkdir(parents=True, exist_ok=False)
    staged = inventory(" syn-01 ", "DUP-01", "DUP-01", "NO-ENDPOINT")
    staged["endpoint"]["bytes"] = xlsx(["NumeroSerie", "Nome do Computador"], [
        ["SYN-01", "ENDPOINT-HOST"], ["DUP-01", "AMBIGUOUS-A"], ["DUP-01", "AMBIGUOUS-B"],
        ["ENDPOINT-ONLY", "UNOFFICIAL"]])
    events: list[dict[str, Any]] = []
    for index, category in enumerate(CATEGORIES[:-1]):
        note = "n" * 2000 if index == 0 else "" if index == 1 else "Nota fictícia " + str(index)
        events.append({"id": "legacy-" + category, "horario": "2026-01-15T12:00:00+00:00" if index == 0 else "invalid-original-date", "comparacao": {
            category: [{"serie": "SYN-01", "computador": "DEMO", "motivo": "Série duplicada" if index == 0 else "Conferência fictícia",
                        "anotacao_id": "row-" + category, "anotacao": note}]}})
    for number, note, label in ((1, "inteiro", "integer"), (1.0, "decimal", "decimal")):
        events.append({"id": "legacy-" + label, "horario": "invalid-original-date", "comparacao": {
            "sem_acesso_14_dias": [{"serie": "NUMERIC", "value": number, "anotacao": note}]}})
    for note, label in (("antiga", "old"), ("", "latest")):
        events.append({"id": "legacy-blank-" + label, "comparacao": {
            "sem_acesso_14_dias": [{"serie": "BLANK", "anotacao": note}]}})
    events.append({"id": "legacy-conflicting", "comparacao": {"sem_acesso_14_dias": [
        {"serie": "CONFLICT", "anotacao": "A"}, {"serie": "CONFLICT", "anotacao": "B"}]}})
    history = {"historico": events, "anotacoes": [{"evento_id": "partial-event", "item_id": "shared-row-stable",
        "categoria": "sem_acesso_14_dias", "serie": "SYN-01", "anotacao": "Sem histórico local",
        "horario": "legacy-invalid", "atualizado_em": "legacy-invalid"}]}
    state = {"unidades": [{"id": 9_000_000_000_001, "cidade": "Cidade fictícia extra", "endereco": "Rua de teste",
                           "uf": "PR", "cep": "00000-000", "cnpj": "00000000000000", "campo_legado": "preservado"}],
        "apelidos": [{"serie": " syn-01 ", "apelido": "MANUAL-HOST"}],
        "historico_apelidos": [{"id": "legacy-alias-001", "horario": "invalid-original-date", "tipo": "edicao",
            "serie": " syn-01 ", "apelido_anterior": "BASE", "apelido_novo": "MANUAL-HOST", "acao": "atualizacao"}]}
    content = {"detalhes": staged["detalhes"]["bytes"], "endpoint": staged["endpoint"]["bytes"],
               "historico": canonical(history).encode(), "estado": canonical(state).encode(),
               "modelo_exportacao": xlsx(["NumeroSerie", "Apelido", "IdCliente"],
                    [["SYN-01", "OLD", "0000"], ["NO-ENDPOINT", "OLD", "0000"]], native=True)}
    # This template is generated by the existing synthetic test helper.
    helpers = importlib.import_module("tests.test_integrity_workflows")
    template_path = helpers.make_transfer_template(root / "transfer-synthetic.xlsx")
    content["modelo_transferencia"] = template_path.read_bytes()
    names = {r: r + (".json" if r in {"historico", "estado"} else ".xlsx") for r in content}
    manifest: dict[str, Any] = {"format": "simpress-migration-bundle-v1", "synthetic": True, "bundle_id": str(uuid.uuid4()), "files": {}}
    for role, data in content.items():
        (root / names[role]).write_bytes(data)
        manifest["files"][role] = {"path": names[role], "sha256": sha(data)}
    (root / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return root
