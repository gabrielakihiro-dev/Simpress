@dataclass
class Arquivo:
    id: str
    nome: str
    formato: str
    dados: bytes
    criado: float

    def publico(self) -> Dict[str, Any]:
        """What the screen needs to build the download button; never the content."""
        return {"id": self.id, "nome": self.nome, "formato": self.formato, "tamanho": len(self.dados)}


class GeradorRelatorios:
    """Builds the reports and keeps them in memory (count, size and time limited). Own lock: downloads run in worker threads."""

    def __init__(
        self,
        api: SimpressApi,
        ttl: float = TTL_SEGUNDOS,
        relogio: Callable[[], float] = time.monotonic,
        agora: Callable[[], datetime] = datetime.now,
        max_relatorios: int = MAX_RELATORIOS,
    ) -> None:
        self._api = api
        self._ttl = ttl
        self._relogio = relogio
        self._agora = agora
        self._max = max_relatorios
        self._lock = threading.Lock()
        self._itens: Dict[str, Arquivo] = {}

    def gerar(self, tipo: Any, formato: Any, mes: Any = None) -> Dict[str, Any]:
        """Validate (closed lists), read the data, build the file and store it. Raises `RelatorioRecusado`."""
        if not isinstance(tipo, str) or tipo not in TIPOS:
            raise RelatorioRecusado(f"Tipo de relatório inválido. Use um destes: {', '.join(TIPOS)}.")
        if not isinstance(formato, str) or formato not in FORMATOS:
            raise RelatorioRecusado(f"Formato inválido. Use um destes: {', '.join(FORMATOS)}.")
        if mes in (None, ""):
            mes = ""
        elif not isinstance(mes, str) or not MES_PATTERN.match(mes):
            raise RelatorioRecusado("Informe o mês no formato AAAA-MM (ex.: 2026-10).")
        relatorio = coletar(self._api, tipo, mes)
        agora = self._agora()
        dados = _xlsx(relatorio) if formato == "xlsx" else _docx(relatorio, agora)
        if len(dados) > MAX_ARQUIVO_BYTES:
            raise RelatorioRecusado("O relatório ficou grande demais para gerar.")
        partes = ["simpress", tipo.replace("_", "-")] + ([mes] if tipo == "resumo_mensal" else []) + [f"{agora:%Y%m%d}"]
        return self._guardar(partes, formato, dados)

    def exportar(self, planilha: Any, data: Any = None) -> Dict[str, Any]:
        """Run the app's own export route and keep the .xlsx it answers, like a report. Raises `RelatorioRecusado`."""
        if not isinstance(planilha, str) or planilha not in PLANILHAS:
            raise RelatorioRecusado(f"Planilha inválida. Use uma destas: {', '.join(PLANILHAS)}.")
        params: Optional[Dict[str, Any]] = None
        if planilha == "historico_comparacoes":
            if not isinstance(data, str) or not DATA_PATTERN.match(data):
                raise RelatorioRecusado("Informe a data do histórico no formato AAAA-MM-DD (ex.: 2026-10-29).")
            params = {"data": data}
        ok, dados = self._api.ler_rota(PLANILHAS[planilha][1], params)
        if not ok:
            raise RelatorioRecusado(str(dados))
        if not isinstance(dados, bytes) or dados[:2] != b"PK":
            raise RelatorioRecusado("O Simpress não devolveu uma planilha.")
        if len(dados) > MAX_ARQUIVO_BYTES:
            raise RelatorioRecusado("A planilha ficou grande demais para exportar.")
        return self._guardar(["simpress", "exportacao", planilha.replace("_", "-")] + ([data] if params else []) + [f"{self._agora():%Y%m%d}"], "xlsx", dados)

    def _guardar(self, partes: List[str], formato: str, dados: bytes) -> Dict[str, Any]:
        arquivo = Arquivo(secrets.token_hex(8), _NOME_SEGURO.sub("-", "-".join(partes)) + f".{formato}", formato, dados, self._relogio())
        with self._lock:
            self._expirar()
            self._itens[arquivo.id] = arquivo
            # Oldest first out: the user cannot delete a report, so a full store makes room instead of refusing.
            while len(self._itens) > self._max or sum(len(a.dados) for a in self._itens.values()) > MAX_TOTAL_BYTES:
                del self._itens[next(iter(self._itens))]
        return arquivo.publico()

    def _expirar(self) -> None:
        limite = self._relogio() - self._ttl
        for id_ in [i for i, a in self._itens.items() if a.criado < limite]:
            del self._itens[id_]

    def obter(self, id_: str) -> Optional[Arquivo]:
        with self._lock:
            self._expirar()
            return self._itens.get(id_)

    def limpar(self) -> None:
        with self._lock:
            self._itens.clear()
