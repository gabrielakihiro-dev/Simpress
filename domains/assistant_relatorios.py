TIPOS: Dict[str, str] = {
    "resumo_mensal": "Resumo mensal",
    "totais_inventario": "Totais do inventário",
    "ultima_comparacao": "Última comparação de planilhas",
    "divergencias_localidade": "Localidades divergentes",
    "chamados_sebrae_abertos": "Chamados Sebrae em aberto",
    "pendencias_operacionais": "Pendências operacionais",
}
FORMATOS: Dict[str, str] = {
    "xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    "docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
}
MES_PATTERN = re.compile(r"^[0-9]{4}-(0[1-9]|1[0-2])$")
DATA_PATTERN = re.compile(r"^[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01])$")
# Spreadsheets the app already exports by route (the file is the route's own answer, never sent to the model).
PLANILHAS: Dict[str, Tuple[str, str]] = {
    "equipamentos": ("Equipamentos (modelo de exportação)", "/api/exportar-equipamentos"),
    "chamados": ("Acompanhamento de chamados", "/api/operacoes/chamados/exportar"),
    "historico_comparacoes": ("Histórico de comparações de um dia (informe a data AAAA-MM-DD)", "/api/historico-comparacoes/exportar/excel"),
    "usuarios_entra": ("Usuários do Entra", "/api/usuarios-entra/exportar"),
}
MSG_PLANILHA_EXPORTADA = "Planilha Exportada com Sucesso!"

TTL_SEGUNDOS = 30 * 60
MAX_RELATORIOS = 10
MAX_TOTAL_BYTES = 30 * 1024 * 1024
MAX_ARQUIVO_BYTES = 10 * 1024 * 1024
MAX_LINHAS = 5000
MAX_CELULA = 2000

_CONTROLE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")
_NOME_SEGURO = re.compile(r"[^A-Za-z0-9._-]")
_ABA_PROIBIDA = re.compile(r"[\[\]:*?/\\]")
_INICIO_FORMULA = ("=", "+", "-", "@")
# Sections of the comparison that are not pending items; labels as on the history screen.
_SECOES_EXTRAS = {
    "apelidos_atualizados": "Apelidos atualizados",
    "divergencias_apelidos_manuais": "Apelidos manuais divergentes",
    "mudancas_usuarios": "Mudanças de usuário logado",
}
_COLUNAS = {
    "serie": "Série", "serial": "Série", "usuario": "Usuário", "usuario_anterior": "Usuário anterior",
    "usuario_novo": "Usuário novo", "observacao": "Observação", "local_detalhes": "Local na Simpress",
    "dias_sem_verificacao": "Dias sem verificação", "dias_sem_acesso": "Dias sem acesso",
}


class RelatorioRecusado(Exception):
    """The report cannot be generated. The message is safe to show and to give to the model."""


def _dict(valor: Any) -> Dict[str, Any]:
    return valor if isinstance(valor, dict) else {}


def _celula(valor: Any) -> Any:
    """Cell value that is safe to write: clean text, bounded size, no formula."""
    if valor is None:
        return ""
    if isinstance(valor, bool):
        return "Sim" if valor else "Não"
    if isinstance(valor, (int, float)):
        return valor
    texto = valor if isinstance(valor, str) else json.dumps(valor, ensure_ascii=False, default=str)
    texto = limpar_texto_sensivel(_CONTROLE.sub(" ", texto))[:MAX_CELULA]
    return "'" + texto if texto.startswith(_INICIO_FORMULA) else texto


@dataclass
class Tabela:
    titulo: str
    colunas: List[str]
    linhas: List[List[Any]]


@dataclass
class Relatorio:
    titulo: str
    detalhe: str
    tabelas: List[Tabela]


def _tabela(titulo: str, colunas: List[str], linhas: List[List[Any]]) -> Tabela:
    if len(linhas) > MAX_LINHAS:
        omitidas = len(linhas) - MAX_LINHAS
        linhas = linhas[:MAX_LINHAS] + [[f"... mais {omitidas} linhas omitidas"] + [""] * (len(colunas) - 1)]
    return Tabela(titulo, colunas, linhas)


def _titulo_coluna(chave: str) -> str:
    if chave in _COLUNAS:
        return _COLUNAS[chave]
    texto = chave.replace("_", " ").capitalize()
    return texto.replace(" na simpress", " na Simpress").replace(" no endpoint", " no Endpoint")


def _tabela_itens(titulo: str, itens: List[Dict[str, Any]]) -> Tabela:
    rotulados = [_dict(_rotular_item(i)) for i in itens]
    chaves = list(dict.fromkeys(k for i in rotulados for k in i))
    if not chaves:
        return Tabela(titulo, ["Item"], [["Nenhum item nesta seção"]])
    return _tabela(titulo, [_titulo_coluna(k) for k in chaves], [[i.get(k) for k in chaves] for i in rotulados])


def _sebrae_fora(categoria: str, item: Dict[str, Any]) -> bool:
    """AGENTS.md: the Sebrae notebook series stay out of the unmatched lists."""
    return categoria.startswith("ausentes_") and is_sebrae_owned_notebook_serial(item.get("serie") or item.get("serial"))


# --- data ---------------------------------------------------------------------------------------------------


def _ler(api: SimpressApi, caminho: str, params: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    ok, dados = api.ler_rota(caminho, params)
    if not ok:
        raise RelatorioRecusado(str(dados))
    return _dict(dados)


def _comparacao(api: SimpressApi) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    evento, detalhe, falha = api.ultimo_evento()
    if falha is not None or evento is None or detalhe is None:
        raise RelatorioRecusado(str((falha or {}).get("erro") or (falha or {}).get("mensagem") or "Histórico indisponível."))
    return evento, _dict(_dict(detalhe.get("evento")).get("comparacao"))


def _resumo_mensal(api: SimpressApi, mes: str) -> Relatorio:
    if not mes:
        raise RelatorioRecusado("Informe o mês do resumo mensal no formato AAAA-MM (ex.: 2026-10).")
    dados = _ler(api, "/api/relatorio-mensal/dados", {"mes": mes})
    rotulo = str(_dict(dados.get("mes")).get("label") or mes)
    linhas = [list(linha) for linha in summary_rows(dados)]
    return Relatorio(f"Resumo mensal — {rotulo}", "", [_tabela("Resumo", ["Bloco", "Indicador", "Valor", "Origem"], linhas)])


def _totais_inventario(api: SimpressApi) -> Relatorio:
    totais = api.obter_totais_inventario()
    if "erro" in totais:
        raise RelatorioRecusado(str(totais["erro"]))
    linhas = [
        ["Equipamentos na base oficial", totais["total_equipamentos_oficial"]],
        ["Unidades", totais["total_unidades"]],
        ["Base importada", totais["base_importada"]],
        ["Arquivo de origem", totais["arquivo_origem"]],
        ["Última atualização", totais["ultima_atualizacao"]],
        ["Alterações pendentes de exportação", totais["alteracoes_exportaveis"]],
    ]
    return Relatorio("Totais do inventário", "", [_tabela("Totais", ["Indicador", "Valor"], linhas)])


def _ultima_comparacao(api: SimpressApi) -> Relatorio:
    evento, comparacao = _comparacao(api)
    secoes: Dict[str, List[Dict[str, Any]]] = {}
    for categoria, rotulo in {**PENDING_CATEGORIES, **_SECOES_EXTRAS}.items():
        itens = comparacao.get(categoria)
        if isinstance(itens, list):
            secoes.setdefault(rotulo, []).extend(i for i in itens if isinstance(i, dict) and not _sebrae_fora(categoria, i))
    horario = str(evento.get("horario") or "")
    resumo = _tabela("Resumo", ["Seção", "Total"], [["Comparação de", horario]] + [[r, len(i)] for r, i in secoes.items()])
    return Relatorio("Última comparação de planilhas", f"Comparação de {horario}", [resumo] + [_tabela_itens(r, i) for r, i in secoes.items()])


def _divergencias_localidade(api: SimpressApi) -> Relatorio:
    evento, comparacao = _comparacao(api)
    itens = [_dict(i) for i in comparacao.get("divergencias_local") or []]
    linhas = [[i.get("serie"), i.get("computador"), i.get("local_previsto"), i.get("local_detalhes")] for i in itens]
    tabela = _tabela("Localidade divergente", ["Série", "Computador", "Local previsto", "Local na Simpress"], linhas)
    return Relatorio("Localidades divergentes", f"Comparação de {evento.get('horario') or ''}", [tabela])


def _chamados_sebrae_abertos(api: SimpressApi) -> Relatorio:
    importado = _dict(_ler(api, "/api/sebrae/novos").get("importado"))
    if not importado:
        raise RelatorioRecusado("Ainda não há Dashboard do Sebrae importado.")
    linhas = []
    for aberto in importado.get("abertos") or []:
        valores = _dict(_dict(aberto).get("valores"))
        # The responsible person's name stays out; only whether one is set.
        linhas.append([
            _dict(aberto).get("numero"), _dict(aberto).get("titulo"), valores.get("B"), valores.get("D"), valores.get("J"),
            bool(str(valores.get("A") or "").strip()),
        ])
    colunas = ["Número", "Título", "Categoria", "Status", "Tipo", "Com responsável"]
    return Relatorio("Chamados Sebrae em aberto", f"Dashboard importado: {importado.get('arquivo') or ''}", [_tabela("Chamados", colunas, linhas)])


def _pendencias_operacionais(api: SimpressApi) -> Relatorio:
    dados = _ler(api, "/api/operacoes/pendencias")
    evento = _dict(dados.get("evento"))
    if not evento:
        raise RelatorioRecusado("Nenhum histórico de comparação registrado até o momento.")
    linhas = []
    for pendencia in dados.get("pendencias") or []:
        pendencia = _dict(pendencia)
        item = _dict(pendencia.get("item"))
        if _sebrae_fora(str(pendencia.get("categoria") or ""), item):
            continue
        linhas.append([pendencia.get("secao"), item.get("serie") or item.get("serial"), item.get("computador"), item.get("motivo")])
    tabela = _tabela("Pendências", ["Seção", "Série", "Computador", "Motivo"], linhas)
    return Relatorio("Pendências operacionais", f"Comparação de {evento.get('horario') or ''}", [tabela])


def coletar(api: SimpressApi, tipo: str, mes: str) -> Relatorio:
    if tipo == "resumo_mensal":
        return _resumo_mensal(api, mes)
    construtores: Dict[str, Callable[[SimpressApi], Relatorio]] = {
        "totais_inventario": _totais_inventario,
        "ultima_comparacao": _ultima_comparacao,
        "divergencias_localidade": _divergencias_localidade,
        "chamados_sebrae_abertos": _chamados_sebrae_abertos,
        "pendencias_operacionais": _pendencias_operacionais,
    }
    return construtores[tipo](api)


