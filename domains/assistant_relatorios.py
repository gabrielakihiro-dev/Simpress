def _nome_aba(titulo: str, usados: Set[str]) -> str:
    base = (_ABA_PROIBIDA.sub(" ", titulo).strip() or "Dados")[:31]
    nome, n = base, 1
    while nome.casefold() in usados:
        n += 1
        nome = f"{base[:28]} {n}"
    usados.add(nome.casefold())
    return nome


def _xlsx(relatorio: Relatorio) -> bytes:
    pasta = Workbook()
    pasta.remove(pasta.active)  # type: ignore[arg-type]
    pasta.properties.title = relatorio.titulo
    usados: Set[str] = set()
    cabecalho = PatternFill("solid", fgColor="10213A")
    for tabela in relatorio.tabelas:
        aba = pasta.create_sheet(_nome_aba(tabela.titulo, usados))
        aba.append([_celula(c) for c in tabela.colunas])
        for linha in tabela.linhas:
            aba.append([_celula(c) for c in linha])
        for celula in aba[1]:
            celula.font = Font(bold=True, color="FFFFFF")
            celula.fill = cabecalho
        aba.freeze_panes = "A2"
        for numero, coluna in enumerate(aba.iter_cols(values_only=True), start=1):
            largura = max((len(str(v)) for v in coluna if v is not None), default=8)
            aba.column_dimensions[get_column_letter(numero)].width = min(60, largura + 2)
    saida = BytesIO()
    pasta.save(saida)
    return saida.getvalue()


_W = 'xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"'
_BORDAS = "".join(f'<w:{lado} w:val="single" w:sz="4" w:space="0" w:color="999999"/>' for lado in ("top", "left", "bottom", "right", "insideH", "insideV"))


def _par(texto: Any, negrito: bool = False, tamanho: int = 20, cor: str = "") -> str:
    propriedades = ("<w:b/>" if negrito else "") + (f'<w:color w:val="{cor}"/>' if cor else "") + f'<w:sz w:val="{tamanho}"/>'
    return f'<w:p><w:r><w:rPr>{propriedades}</w:rPr><w:t xml:space="preserve">{escape(str(texto))}</w:t></w:r></w:p>'


def _tabela_docx(tabela: Tabela) -> str:
    largura = 15000 // max(1, len(tabela.colunas))
    grade = "".join(f'<w:gridCol w:w="{largura}"/>' for _ in tabela.colunas)
    cabecalho = "".join(
        f'<w:tc><w:tcPr><w:tcW w:w="{largura}" w:type="dxa"/><w:shd w:val="clear" w:color="auto" w:fill="10213A"/></w:tcPr>'
        f"{_par(_celula(c), True, 18, 'FFFFFF')}</w:tc>"
        for c in tabela.colunas
    )
    linhas = "".join(
        "<w:tr>" + "".join(f'<w:tc><w:tcPr><w:tcW w:w="{largura}" w:type="dxa"/></w:tcPr>{_par(_celula(c), False, 18)}</w:tc>' for c in linha) + "</w:tr>"
        for linha in tabela.linhas
    )
    return (
        f'<w:tbl><w:tblPr><w:tblW w:w="5000" w:type="pct"/><w:tblBorders>{_BORDAS}</w:tblBorders></w:tblPr>'
        f"<w:tblGrid>{grade}</w:tblGrid><w:tr><w:trPr><w:tblHeader/></w:trPr>{cabecalho}</w:tr>{linhas}</w:tbl><w:p/>"
    )


def _docx(relatorio: Relatorio, gerado_em: datetime) -> bytes:
    corpo = _par(_celula(relatorio.titulo), True, 36)
    if relatorio.detalhe:
        corpo += _par(_celula(relatorio.detalhe))
    corpo += _par(f"Gerado em {gerado_em:%d/%m/%Y %H:%M}")
    for tabela in relatorio.tabelas:
        corpo += _par(_celula(tabela.titulo), True, 26) + _tabela_docx(tabela)
    pagina = '<w:sectPr><w:pgSz w:w="16838" w:h="11906" w:orient="landscape"/><w:pgMar w:top="720" w:right="720" w:bottom="720" w:left="720" w:header="360" w:footer="360" w:gutter="0"/></w:sectPr>'
    documento = f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document {_W}><w:body>{corpo}{pagina}</w:body></w:document>'
    tipos = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
        "</Types>"
    )
    relacoes = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>'
        "</Relationships>"
    )
    saida = BytesIO()
    with zipfile.ZipFile(saida, "w", zipfile.ZIP_DEFLATED) as arquivo:
        arquivo.writestr("[Content_Types].xml", tipos)
        arquivo.writestr("_rels/.rels", relacoes)
        arquivo.writestr("word/document.xml", documento.encode("utf-8", "replace"))
    return saida.getvalue()


