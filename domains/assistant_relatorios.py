"""Report files (.xlsx and .docx) the assistant generates on request, kept only in memory.

The AI picks a closed `tipo`, a `formato` and (for the monthly summary) a month: it never writes the content.
The server reads the data through the same internal routes the screens use (`SimpressApi.ler_rota`), builds the
file here and keeps it in memory for `TTL_SEGUNDOS`. Nothing is written to disk, to `data/` or to the Git tree.
The file is served by `GET /api/assistente/relatorio/{id}`, only for ids generated by this server run.

Every cell passes `_celula`: CPF, e-mail, phone and passwords are cleaned and text that Excel could read as a
formula gets a leading apostrophe. The content is for the user to read, so it is never sent to the model.
"""

